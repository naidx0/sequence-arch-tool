/* Builds marks.ts from raw SVGs fetched once with curl (see SOURCES.md).
   usage: node build-marks.mjs <dir with prov/ and agent/> <providers.txt>
   Sanitise: only path and shape elements survive; no scripts, styles, images, gradients, masks,
   clip paths, filters, event handlers or hrefs; every colour becomes currentColor. A file that
   needs anything else to look right (white cut-outs, patterns, raster) gets no mark: the page
   draws a monogram instead. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { sanitise } from './sanitise.mjs';

const [dir, provList] = process.argv.slice(2);
const here = dirname(fileURLToPath(import.meta.url));
const FAKE_DEFAULT = '4d6f6f6e'; // placeholder; the models.dev stand-in sparkle is detected by hash below

const hash = (s) => s.length + ':' + s.replace(/\s+/g, '').slice(0, 60);
const providers = readFileSync(provList, 'utf8').split(/\r?\n/).filter(Boolean);
const AGENT_FILES = { gemini: 'gemini', opencode: 'opencode', 'github-copilot-cli': 'github-copilot-cli', cursor: 'cursor', goose: 'goose', 'qwen-code': 'qwen-code', cline: 'cline', kimi: 'kimi', auggie: 'auggie', 'factory-droid': 'factory-droid', kilo: 'kilo', 'mistral-vibe': 'mistral-vibe', 'claude-acp': 'claude-acp', 'codex-acp': 'codex-acp', 'amp-acp': 'amp-acp' };
const SPARKLE = 'M9.8132 15.9038L9 18.75';
const marks = { agent: {}, provider: {} };
const rejected = [];
for (const [id, f] of Object.entries(AGENT_FILES)) {
  const p = join(dir, 'agent', `${f}.svg`);
  const s = existsSync(p) ? sanitise(readFileSync(p, "utf8"), 8000) : null;
  if (s) marks.agent[id] = s; else rejected.push(`agent:${id}`);
}
for (const id of providers) {
  const raw = readFileSync(join(dir, 'prov', `${id}.svg`), 'utf8');
  if (raw.includes(SPARKLE)) { rejected.push(`provider:${id} (models.dev stand-in)`); continue; }
  const s = sanitise(raw);
  if (s) marks.provider[id] = s; else rejected.push(`provider:${id}`);
}
const entry = (v) => JSON.stringify([v.vb, v.body, v.rootFill]);
const head = (what) => `/* Generated by build-marks.mjs from the files listed in SOURCES.md. Do not edit by hand.
   ${what} Each mark: [viewBox, shapes, root fill]. Every colour is currentColor. */

import type { Mark } from './mark';

`;
let ag = head('Agent marks, by ACP registry id.') + `export const AGENT_MARKS: Readonly<Record<string, Mark>> = {\n`;
for (const [k, v] of Object.entries(marks.agent)) ag += `  ${JSON.stringify(k)}: ${entry(v)},\n`;
ag += `};\n`;
let pv = head('Provider marks, by models.dev provider id.') + `export const PROVIDER_MARKS: Readonly<Record<string, Mark>> = {\n`;
for (const [k, v] of Object.entries(marks.provider)) pv += `  ${JSON.stringify(k)}: ${entry(v)},\n`;
pv += `};\n`;
writeFileSync(join(here, 'agentMarks.ts'), ag, 'utf8');
writeFileSync(join(here, 'providerMarks.ts'), pv, 'utf8');
console.log(JSON.stringify({ agents: Object.keys(marks.agent).length, providers: Object.keys(marks.provider).length, agentBytes: Buffer.byteLength(ag), providerBytes: Buffer.byteLength(pv), rejected }, null, 1));
