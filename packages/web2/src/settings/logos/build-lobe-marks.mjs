/* Builds lobeMarks.ts: vendor mono marks taken from @lobehub/icons-static-svg 1.95.1 (MIT, see SOURCES.md),
   fetched once with curl into <dir>/<file>.svg and sanitised by sanitise.mjs.
   usage: node build-lobe-marks.mjs <dir> */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { sanitise } from './sanitise.mjs';

const dir = process.argv[2];
const here = dirname(fileURLToPath(import.meta.url));
/* id the app uses -> file in the package's icons/ folder */
const FILES = { hermes: 'nousresearch' };
let out = `/* Generated by build-lobe-marks.mjs from the lobehub files listed in SOURCES.md. Do not edit by hand.
   Agent marks the ACP registry set lacks or draws badly. Each mark: [viewBox, shapes, root fill]. Every colour is currentColor. */

import type { Mark } from './mark';

export const LOBE_MARKS: Readonly<Record<string, Mark>> = {\n`;
for (const [id, f] of Object.entries(FILES)) {
  const s = sanitise(readFileSync(join(dir, `${f}.svg`), 'utf8'), 30000);
  if (!s) throw new Error(`${f} did not sanitise`);
  out += `  ${JSON.stringify(id)}: ${JSON.stringify([s.vb, s.body, s.rootFill])},\n`;
}
out += `};\n`;
writeFileSync(join(here, 'lobeMarks.ts'), out, 'utf8');
console.log(Object.keys(FILES), Buffer.byteLength(out));
