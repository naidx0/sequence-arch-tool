/* ══════════════════════════════════════════════════════════════════════════
   A SYNTHETIC FAST STREAM (S6), BUILT FROM A REAL RECORDING
   packages/analyzer/src/test/support/fastStreamFixture.ts

   NOT A RECORDING. The codex recordings stream at 3 to 6 text deltas a
   second, too slow to show what a 50 ms merge window does to a fast model.
   This takes codex/todo-plan.jsonl and keeps every frame the client and agent
   exchanged, in order (the tool calls stay where they were), but:
     - each recorded text delta becomes DELTAS_PER_RECORDED synthetic deltas,
       one every 1000/RATE_PER_SEC ms (about 60 a second, ~20 s of text);
     - every other gap is capped at OTHER_GAP_CAP_MS, so the turn stays dense;
     - each agent message's completed text is the synthetic text, so the
       stream and the item agree.
   The header says so: scenario `fast-stream-synthetic`, live: false.
   ══════════════════════════════════════════════════════════════════════════ */

import type { Fixture, Frame, Json } from '@sequence/acp/dist/replay/fixture.js';

import { replayFixture } from './agentServer.js';

export const RATE_PER_SEC = 60;
export const DELTAS_PER_RECORDED = 8;
export const OTHER_GAP_CAP_MS = 300;

const WORDS = ['the', 'plan', 'reads', 'main', 'route', 'and', 'checks', 'each', 'step', 'before', 'moving', 'on'];

export function fastStreamFixture(): Fixture {
  const base = replayFixture('codex', 'todo-plan');
  const frames: Frame[] = [];
  const textByItem = new Map<string, string>();
  let t = 0;
  let lastRecorded = base.frames[0]?.t ?? 0;
  let piece = 0;
  for (const f of base.frames) {
    const msg = f.msg as Json;
    if (msg.method === 'item/agentMessage/delta') {
      const params = msg.params as Json;
      const item = String(params.itemId);
      for (let k = 0; k < DELTAS_PER_RECORDED; k++) {
        t += 1000 / RATE_PER_SEC;
        const text = `${WORDS[piece % WORDS.length]} `;
        piece++;
        textByItem.set(item, (textByItem.get(item) ?? '') + text);
        frames.push({ ...f, t: Math.round(t), msg: { ...msg, params: { ...params, delta: text } } });
      }
      lastRecorded = f.t;
      continue;
    }
    t += Math.min(Math.max(0, f.t - lastRecorded), OTHER_GAP_CAP_MS);
    lastRecorded = f.t;
    frames.push({ ...f, t: Math.round(t) });
  }
  /* The completed agent messages carry the synthetic text. */
  const patched = frames.map((f) => {
    const msg = f.msg as Json;
    const item = (msg.params as Json | undefined)?.item as Json | undefined;
    if (msg.method === 'item/completed' && item?.type === 'agentMessage' && textByItem.has(String(item.id))) {
      return { ...f, msg: { ...msg, params: { ...(msg.params as Json), item: { ...item, text: textByItem.get(String(item.id)) } } } };
    }
    return f;
  });
  return {
    ...base,
    header: {
      ...base.header,
      scenario: 'fast-stream-synthetic',
      live: false,
      covers: `SYNTHETIC, not recorded: codex/todo-plan with each text delta split into ${DELTAS_PER_RECORDED} at ${RATE_PER_SEC}/s and other gaps capped at ${OTHER_GAP_CAP_MS} ms`,
      source: 'generated by packages/analyzer/src/test/support/fastStreamFixture.ts from codex/todo-plan.jsonl',
    },
    frames: patched,
  };
}
