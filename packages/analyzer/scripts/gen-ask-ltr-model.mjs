#!/usr/bin/env node
/*
 * Regenerate src/explain/askLtrModel.generated.ts from a LightGBM text model
 * (the frozen harness-study search3/ltr model.txt). The model ships as a TS
 * string constant so it lands in dist/ and in the server bundle with no asset
 * copying and no path lookup (Windows-safe). Only the header and the trees are
 * kept; the parameters section is training metadata.
 *
 *   node packages/analyzer/scripts/gen-ask-ltr-model.mjs <model.txt>
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) throw new Error('usage: gen-ask-ltr-model.mjs <model.txt>');
const raw = fs.readFileSync(src, 'utf8').replace(/\r\n/g, '\n');
const end = raw.indexOf('\nend of trees');
if (end < 0) throw new Error('not a LightGBM text model (no "end of trees")');
const kept = raw.slice(0, end) + '\nend of trees\n';
const sha = crypto.createHash('sha256').update(raw).digest('hex');
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'explain', 'askLtrModel.generated.ts');
fs.writeFileSync(
  out,
  `/* GENERATED by packages/analyzer/scripts/gen-ask-ltr-model.mjs — do not edit.\n` +
    ` * Source: harness-study search3/ltr/model.txt (LightGBM 4.7.0 LambdaRank, 150 trees, 39 features)\n` +
    ` * sha256 of the source file: ${sha}\n` +
    ` * Header and trees only (the parameters section is dropped). */\n` +
    `export const ASK_LTR_MODEL_SHA256 = '${sha}';\n` +
    `export const ASK_LTR_MODEL_TEXT = ${JSON.stringify(kept)};\n`,
);
console.log(`wrote ${out} (${kept.length} chars, source sha256 ${sha.slice(0, 16)})`);
