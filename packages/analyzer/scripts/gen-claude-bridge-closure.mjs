#!/usr/bin/env node
/* Regenerates src/server/claudeBridgeClosure.ts: the pinned dependency closure of the Claude ACP bridge, as an
   exact npm node_modules layout (path, version, sha512 integrity, tarball URL).
   It is built from the workspace's own pnpm-lock.yaml (the bridge is an analyzer devDependency), following the
   bridge's snapshot through its dependencies and peers and leaving optional packages (the Agent SDK's ~250 MB
   native claude binaries) out. So the tree the app downloads is, version for version, the tree the tests and the
   prepare-server check run. Needs no network and no npm.
   Layout: a package is hoisted to the top node_modules when no other version holds the name, else nested under
   each dependent that needs it, so Node's resolution finds the version the lock chose.
   Usage: node scripts/gen-claude-bridge-closure.mjs   (after pnpm install; the version is the analyzer devDependency) */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const here = path.dirname(fileURLToPath(import.meta.url));
const PKG = '@agentclientprotocol/claude-agent-acp';
const version = JSON.parse(fs.readFileSync(path.join(here, '..', 'package.json'), 'utf8')).devDependencies[PKG];
if (!/^\d+\.\d+\.\d+$/.test(version ?? '')) throw new Error(`${PKG} must be pinned to an exact version in package.json, got ${version}`);

const doc = YAML.parse(fs.readFileSync(path.join(here, '..', '..', '..', 'pnpm-lock.yaml'), 'utf8'));
const snaps = doc.snapshots;
const pkgs = doc.packages;
const splitKey = (key) => {
  const name = key.startsWith('@') ? '@' + key.slice(1).split('@')[0] : key.split('@')[0];
  return { name, ver: key.slice(name.length + 1).split('(')[0] };
};
const rootKey = Object.keys(snaps).find((k) => k.startsWith(`${PKG}@${version}`));
if (!rootKey) throw new Error(`${PKG}@${version} is not in pnpm-lock.yaml: run pnpm install first`);

/* placed: path -> {name, ver, key}. lookup(fromPath, name) walks up node_modules like Node does. */
const placed = new Map();
const lookup = (from, name) => {
  for (let base = from; ; ) {
    const p = base === '' ? `node_modules/${name}` : `${base}/node_modules/${name}`;
    if (placed.has(p)) return placed.get(p);
    if (base === '') return null;
    const i = base.lastIndexOf('/node_modules/');
    base = i < 0 ? '' : base.slice(0, i);
  }
};
const place = (p, key) => {
  const { name, ver } = splitKey(key);
  placed.set(p, { name, ver, key });
  return p;
};
const queue = [place(`node_modules/${PKG}`, rootKey)];
while (queue.length) {
  const parent = queue.shift();
  const parentKey = placed.get(parent).key;
  for (const [n, v] of Object.entries(snaps[parentKey]?.dependencies ?? {})) {
    const key = `${n}@${v}`;
    const want = splitKey(key).ver;
    const have = lookup(parent, n);
    if (have && have.ver === want) continue;
    const top = `node_modules/${n}`;
    queue.push(place(placed.has(top) ? `${parent}/node_modules/${n}` : top, key));
  }
}

const packages = [...placed.entries()]
  .map(([p, { name, ver }]) => {
    const meta = pkgs[`${name}@${ver}`];
    const integrity = meta?.resolution?.integrity;
    const base = name.split('/').pop();
    return { path: p, name, version: ver, integrity, resolved: `https://registry.npmjs.org/${name}/-/${base}-${ver}.tgz`, license: meta?.license ?? null };
  })
  .sort((a, b) => a.path.localeCompare(b.path));
for (const p of packages) if (!/^sha512-/.test(p.integrity ?? '')) throw new Error(`${p.path}: the pnpm lock has no sha512 integrity`);

const out = `/* GENERATED by scripts/gen-claude-bridge-closure.mjs from pnpm-lock.yaml. Do not edit. */\nexport interface BridgePackage { path: string; name: string; version: string; integrity: string; resolved: string; license: string | null }\nexport const CLAUDE_BRIDGE_PACKAGE = ${JSON.stringify(PKG)};\nexport const CLAUDE_BRIDGE_VERSION = ${JSON.stringify(version)};\n/** Where the bridge's entry sits inside the extracted tree. */\nexport const CLAUDE_BRIDGE_ENTRY = 'node_modules/${PKG}/dist/index.js';\nexport const CLAUDE_BRIDGE_CLOSURE: readonly BridgePackage[] = ${JSON.stringify(packages, null, 1)};\n`;
fs.writeFileSync(path.join(here, '..', 'src', 'server', 'claudeBridgeClosure.ts'), out);
console.log(`gen-claude-bridge-closure: ${packages.length} packages for ${PKG}@${version}`);
