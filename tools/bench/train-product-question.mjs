#!/usr/bin/env node
/**
 * Trains the product-vs-code question classifier (naive Bayes over words and word
 * pairs) and writes packages/analyzer/src/server/productQuestionModel.ts.
 *
 *   node tools/bench/train-product-question.mjs [--eval heldout.json]
 *
 * The threshold is picked on 5 training folds so that at most 1% of code questions
 * score above it; the held-out set is only read with --eval.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'tools/bench/data/product-question-train.json'), 'utf8'));

/* Must match productQuestionTokens in askPipeline.ts. */
const tok = (q) => {
  const w = q.toLowerCase().replace(/[^a-z0-9' ]+/g, ' ').split(/\s+/).filter(Boolean);
  const out = [...w];
  for (let i = 0; i + 1 < w.length; i++) out.push(`${w[i]}_${w[i + 1]}`);
  if (/\b[\w-]+\.(py|ts|tsx|js|go|java|rs|json)\b|`|\(\)/.test(q)) out.push('__codeish');
  return out;
};
function train(rows) {
  const c = { product: new Map(), code: new Map() }, n = { product: 0, code: 0 }, docs = { product: 0, code: 0 };
  const V = new Set();
  for (const r of rows) {
    docs[r.label]++;
    for (const t of tok(r.question)) { c[r.label].set(t, (c[r.label].get(t) || 0) + 1); n[r.label]++; V.add(t); }
  }
  return { c, n, docs, V: V.size };
}
function score(m, q) {
  let s = Math.log(m.docs.product / m.docs.code);
  for (const t of tok(q)) {
    s += Math.log(((m.c.product.get(t) || 0) + 1) / (m.n.product + m.V)) - Math.log(((m.c.code.get(t) || 0) + 1) / (m.n.code + m.V));
  }
  return s;
}

const shuf = data.map((r, i) => [r, (i * 2654435761) % 1000]).sort((a, b) => a[1] - b[1]).map((x) => x[0]);
const folds = [];
for (let k = 0; k < 5; k++) {
  const m = train(shuf.filter((_, i) => i % 5 !== k));
  for (const r of shuf.filter((_, i) => i % 5 === k)) folds.push([score(m, r.question), r.label]);
}
const codeS = folds.filter((x) => x[1] === 'code').map((x) => x[0]).sort((a, b) => b - a);
const threshold = codeS[Math.floor(codeS.length * 0.01)] ?? 0;
const prodS = folds.filter((x) => x[1] === 'product').map((x) => x[0]);
console.log(`rows ${data.length}; fold threshold ${threshold.toFixed(2)}; fold recall ${prodS.filter((s) => s > threshold).length}/${prodS.length}`);

const m = train(data);
const model = { threshold, docs: m.docs, n: m.n, V: m.V, product: Object.fromEntries(m.c.product), code: Object.fromEntries(m.c.code) };
const out =
  '/* GENERATED by tools/bench/train-product-question.mjs from ' + data.length + ' labelled questions\n' +
  '   (train8 + bank 6 openers + teach-eval code questions). Do not edit by hand. */\n' +
  'export const PRODUCT_QUESTION_MODEL = ' + JSON.stringify(model) + ' as const;\n';
fs.writeFileSync(path.join(root, 'packages/analyzer/src/server/productQuestionModel.ts'), out.replace(/\n/g, '\r\n'));

const ev = process.argv.indexOf('--eval');
if (ev > 0) {
  const H = JSON.parse(fs.readFileSync(process.argv[ev + 1], 'utf8'));
  let tp = 0, fp = 0, np = 0, nc = 0;
  for (const x of H) {
    const hit = score(m, x.question) > threshold;
    if (x.label === 'product') { np++; if (hit) tp++; } else { nc++; if (hit) fp++; }
  }
  console.log(`held-out: product ${tp}/${np}, code false hits ${fp}/${nc}`);
}
