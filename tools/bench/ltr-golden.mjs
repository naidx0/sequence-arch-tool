#!/usr/bin/env node
/*
 * ltr-golden — write packages/analyzer/test/fixtures/ltr-golden.json from the
 * Python reference (harness-study search3/ltr: ltrlib.features + model.txt).
 *
 * Builds the tiny golden repo (src/test/ltrGoldenRepo.ts, from dist), runs
 * ltrlib on it, and records per question the candidates (in order), the 39
 * feature rows and pick.py's full order; plus 60 model rows whose split feature
 * sits EXACTLY on a tree's root threshold, with LightGBM's raw scores.
 * ask-ltr.test.ts asserts the TS port against it with no Python present.
 *
 *   node tools/bench/ltr-golden.mjs [--python <venv python>] [--ltr <search3/ltr dir>]
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildLtrGoldenRepo, LTR_GOLDEN_HIST_N, LTR_GOLDEN_QUESTIONS } from '../../packages/analyzer/dist/test/ltrGoldenRepo.js';

const arg = (n, d) => {
  const i = process.argv.indexOf(n);
  return i === -1 ? d : process.argv[i + 1];
};
const PY = arg('--python', '/home/claude/ltr-venv/bin/python');
const LTR = arg('--ltr', '/mnt/project-files/sequence/harness-study/search3/ltr');
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(ROOT, 'packages', 'analyzer', 'test', 'fixtures', 'ltr-golden.json');

const dir = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'ltr-golden-')));
buildLtrGoldenRepo(dir);
const script = `
import json, sys, random
sys.path.insert(0, ${JSON.stringify(LTR)})
import numpy as np, lightgbm as lgb
from ltrlib import Snapshot, features, FEATURES
repo, hist_n, qs = sys.argv[1], int(sys.argv[2]), json.loads(sys.argv[3])
model = lgb.Booster(model_file=${JSON.stringify(path.join(LTR, 'model.txt'))})
snap = Snapshot(repo, idx=0, back=0, hist_n=hist_n, questions=False)
out = {'S': snap.S, 'files': sorted(snap.raw.keys()), 'questions': []}
r = FEATURES.index('f50_rank')
for q in qs:
    cands, X = features(snap, q)
    s = model.predict(np.array(X, dtype=np.float64)) if cands else []
    order = sorted(range(len(cands)), key=lambda i: (-s[i], X[i][r], cands[i]))
    out['questions'].append({'q': q, 'cands': cands, 'rows': X, 'scores': [float(x) for x in s], 'top5': [cands[i] for i in order[:5]], 'order': [cands[i] for i in order]})
# Rows on the split thresholds: each tree's root feature set exactly to its threshold.
d = model.dump_model()
rng = random.Random(7)
info = [x for x in d['feature_infos'].values()]
rows = []
for t in d['tree_info'][:60]:
    root = t['tree_structure']
    row = []
    for fi in info:
        lo, hi = float(fi['min_value']), float(fi['max_value'])
        row.append(rng.uniform(lo, hi) if rng.random() < 0.7 else 0.0)
    row[root['split_feature']] = float(root['threshold'])
    rows.append(row)
out['threshold_rows'] = rows
out['threshold_scores'] = [float(x) for x in model.predict(np.array(rows, dtype=np.float64))]
print(json.dumps(out))
`;
const res = JSON.parse(execFileSync(PY, ['-B', '-c', script, dir, String(LTR_GOLDEN_HIST_N), JSON.stringify(LTR_GOLDEN_QUESTIONS)], { encoding: 'utf8', maxBuffer: 1 << 28 }));
const fixture = {
  about: 'Generated by tools/bench/ltr-golden.mjs from harness-study search3/ltr (ltrlib.features, pick.py ordering, LightGBM 4.7.0 on model.txt) over the repo src/test/ltrGoldenRepo.ts builds. Do not edit by hand.',
  histN: LTR_GOLDEN_HIST_N,
  ...res,
};
delete fixture.S;
fs.writeFileSync(OUT, JSON.stringify(fixture) + '\n');
console.log(`wrote ${OUT}: ${res.files.length} files, ${res.questions.length} questions, ${res.questions.reduce((n, q) => n + q.cands.length, 0)} candidate rows, ${res.threshold_rows.length} threshold rows`);
fs.rmSync(dir, { recursive: true, force: true });
